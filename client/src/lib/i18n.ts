export type TKey = keyof typeof T;

/** The text of ``key`` in ``lang``, with ``{name}`` placeholders replaced. */
export function tr(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s: string = T[key][lang];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Current display language of the supply tables (FR | EN buttons) and a bound translator. */
export function useLang(): { lang: Lang; t: (key: TKey, vars?: Record<string, string | number>) => string } {
  const { perimeter } = usePerimeter();
  const lang: Lang = perimeter.lang === "en" ? "en" : "fr";
  return { lang, t: (key, vars) => tr(lang, key, vars) };
}
